#!/usr/bin/env python3
"""gen-provider-schemas.py - regenerates tests/provider-schemas.json from the PINNED provider packages.

For every Provider in packages/packages.yaml, downloads the package layer of the exact digest from the
upstream registry (anonymous pull, the same index Harbor mirrors) and keeps, for each managed resource
kind that a recipe Composition uses, the flattened field paths of spec and status with their types.
tests/test-serverless.py validates every base field and every patch path against this file, and fails
when a digest in packages.yaml is not the digest the fixture was generated from.

Network only here (run it after bumping a provider); the test itself is offline.
  gen-provider-schemas.py            rewrite the fixture
"""
import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
COMPONENT = HERE.parent
OUT = HERE / "provider-schemas.json"
ACCEPT = ("application/vnd.oci.image.index.v1+json, application/vnd.oci.image.manifest.v1+json, "
          "application/vnd.docker.distribution.manifest.v2+json")
UPSTREAM = "xpkg.crossplane.io"


def _get(url, tok, accept=ACCEPT):
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {tok}", "Accept": accept})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def package_yaml(repo, digest):
    tok = json.load(urllib.request.urlopen(
        f"https://ghcr.io/token?service=ghcr.io&scope=repository:{repo}:pull", timeout=15))["token"]
    base = f"https://{UPSTREAM}/v2/{repo}"
    man = json.loads(_get(f"{base}/manifests/{digest}", tok))
    if "manifests" in man:
        m = next(m for m in man["manifests"] if m.get("platform", {}).get("architecture") == "amd64")
        man = json.loads(_get(f"{base}/manifests/{m['digest']}", tok))
    layer = next(l for l in man["layers"] if (l.get("annotations") or {}).get("io.crossplane.xpkg") == "base")
    with tarfile.open(fileobj=io.BytesIO(_get(f"{base}/blobs/{layer['digest']}", tok, "*/*"))) as tf:
        member = next(m for m in tf.getmembers() if m.name.endswith("package.yaml"))
        return tf.extractfile(member).read()


def flatten(schema, prefix=""):
    """{path: type}; arrays add [], maps (additionalProperties) are typed map."""
    out = {}
    t = schema.get("type")
    if t == "object" and schema.get("properties"):
        for k, v in schema["properties"].items():
            p = f"{prefix}.{k}" if prefix else k
            vt = v.get("type")
            out[p] = "map" if vt == "object" and "additionalProperties" in v and not v.get("properties") else vt
            out.update(flatten(v, p))
    elif t == "array" and "items" in schema:
        out.update(flatten(schema["items"], prefix + "[]"))
    return out


def used_kinds():
    """(group, version, kind) of every managed resource the recipe Compositions compose."""
    kinds = set()
    for f in sorted((COMPONENT / "recipes").glob("*.yaml")):
        for d in yaml.safe_load_all(f.read_text()):
            if not d or d.get("kind") != "Composition":
                continue
            for step in d["spec"]["pipeline"]:
                for r in (step.get("input") or {}).get("resources", []):
                    g, v = r["base"]["apiVersion"].split("/")
                    if g.endswith(".aws.m.upbound.io"):
                        kinds.add((g, v, r["base"]["kind"]))
    return kinds


def main():
    pk = [d for d in yaml.safe_load_all((COMPONENT / "packages" / "packages.yaml").read_text())
          if d and d.get("kind") == "Provider" and d["metadata"]["name"] != "provider-family-aws"]
    want = used_kinds()
    out = {"_doc": "Generated by gen-provider-schemas.py from the provider package digests below. Do not edit.",
           "packages": {}, "kinds": {}}
    for p in pk:
        m = re.fullmatch(r"harbor\.local/(.+):([^@]+)@(sha256:[0-9a-f]{64})", p["spec"]["package"])
        repo, tag, digest = m.groups()
        out["packages"][p["metadata"]["name"]] = f"{UPSTREAM}/{repo}:{tag}@{digest}"
        for crd in yaml.safe_load_all(package_yaml(repo, digest)):
            if not crd or crd.get("kind") != "CustomResourceDefinition":
                continue
            g, k = crd["spec"]["group"], crd["spec"]["names"]["kind"]
            for v in crd["spec"]["versions"]:
                if (g, v["name"], k) in want:
                    root = v["schema"]["openAPIV3Schema"]["properties"]
                    fields = {p2: t for p2, t in flatten({"type": "object", "properties": {
                        "spec": root["spec"], "status": root.get("status", {"type": "object"})}}).items()
                        if not p2.startswith(("spec.initProvider", "status.conditions"))}
                    out["kinds"][f"{g}/{v['name']}/{k}"] = {"provider": p["metadata"]["name"],
                                                            "scope": crd["spec"]["scope"], "fields": fields}
    missing = sorted("/".join(k) for k in want if "/".join(k) not in out["kinds"])
    if missing:
        sys.exit(f"gen-provider-schemas.py: kinds used by the recipes but absent from the packages: {missing}")
    OUT.write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    print(f"gen-provider-schemas.py: {len(out['kinds'])} kinds from {len(out['packages'])} packages -> {OUT.name}")


if __name__ == "__main__":
    main()

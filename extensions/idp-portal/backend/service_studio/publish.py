"""Publication: a reviewed ServiceDraft becomes a branch, one commit and a merge request.

Same seam as the Agent Builder: any object with `call(method, path, body=None) -> (status,
body)`. No cluster client, no AWS client, nothing merged, nothing pushed to `main`. The MR
is the review gate (ADR-0004), CI revalidates, and GitOps (mirror + Argo CD) is the only
path from Git to the cluster. Every write is confined to one package directory, which is
also why reverting the MR removes the capability from the catalog without touching
`platform/instances/` or `platform/compositions/`.

The one file outside the package is `backend/platform_assistant/capability-index.json`, and only
in the shape `with_capability_index` gives it: regenerated by the canonical builder
(`platform_assistant.catalog`) from main's catalog with this commit's package actions applied. It
is a cache of the catalog, so a package MR without it fails the byte comparison in the suite. Its
bytes never come from the request, the browser or the model; `verify_index` regenerates them in
the CI and refuses any difference.

Base pinning (finding M3): the CI reads main's head SHA from GitLab, builds the index and reads the
base package from THAT commit, and sets `base_sha` on the plan. `scaffold` then re-reads the head
right before the commit and refuses `stale_base` when main moved, and the commit starts from
`start_sha = base_sha`, so the index always describes the tree the branch was cut from.
"""
from __future__ import annotations

import base64
import re
import shutil
import tempfile
import urllib.parse
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Any, Mapping, Protocol

from .compiler import (
    FILES, assert_package_paths, breaking_changes, compile_package, diff_drafts, draft_sha256, package_dir,
    policy_verdict,
)
from .compositions import Composition
from .contract import (
    COMPILER, DRAFT_OPS, FIELD_KEYS, OP_CREATE, OP_DEPRECATE, OP_EVOLVE, OP_RETIRE, OPS, SCHEMA_VERSION,
)
from .validator import normalize_draft, validate_draft

TARGET_BRANCH = "main"
MR_LABELS = "service-studio,catalog"
PERSISTED_STATUSES = ("pending", "processing", "mr_open", "merged", "failed", "closed")
_REQUEST_ID = re.compile(r"[0-9a-f]{32}")
_SHA = re.compile(r"[0-9a-f]{40}")
# The only path outside the package a Studio commit may touch, and the two trees its builder reads.
INDEX_PATH = "backend/platform_assistant/capability-index.json"
_INDEX_INPUTS = ("platform/catalog", "platform/compositions")
_JSON_TO_FIELD = {"string": "string", "integer": "integer", "boolean": "boolean", "object": "stringMap", "array": "stringList"}


class PublishRefused(RuntimeError):
    CODES = ("invalid_draft", "already_exists", "not_found", "breaking_change", "duplicate", "mr_merged",
             "mr_closed", "gitlab_error", "manifest_mismatch", "stale_base")

    def __init__(self, code: str, detail: str) -> None:
        assert code in self.CODES, code
        super().__init__(detail)
        self.code, self.detail = code, detail


class GitLabPort(Protocol):
    def call(self, method: str, path: str, body: dict[str, Any] | None = None) -> tuple[int, Any]:
        ...


# ------------------------------------------------------------------ package -> draft
def draft_from_package(capability: Mapping[str, Any], schema: Mapping[str, Any]) -> dict[str, Any]:
    """Rebuild the draft a package means, from its already-parsed capability.yaml and schema.json.

    The caller parses (the CI has PyYAML). Used for the base of `evolve`/`deprecate`, so the
    diff and the breaking-change check run against what is really on `main`.
    """
    meta, spec = capability["metadata"], capability["spec"]
    required = set(schema.get("required") or [])
    fields = []
    for name, prop in (schema.get("properties") or {}).items():
        item: dict[str, Any] = {"name": name, "type": _JSON_TO_FIELD.get(str(prop.get("type")), str(prop.get("type")))}
        for key in ("title", "description", "enum", "minimum", "maximum", "default"):
            if key in prop:
                item[key] = prop[key]
        pattern = prop.get("pattern")
        if isinstance(pattern, str) and not (name == "name" and pattern == "^[a-z0-9]([-a-z0-9]*[a-z0-9])?$"):
            item["pattern"] = pattern[4:-2] if pattern.startswith("^(?:") and pattern.endswith(")$") else pattern
        if isinstance(prop.get("examples"), list) and prop["examples"]:
            item["example"] = prop["examples"][0]
        item["required"] = name in required
        fields.append({k: item[k] for k in FIELD_KEYS if k in item})
    draft: dict[str, Any] = {
        "schemaVersion": SCHEMA_VERSION, "domain": meta["domain"], "name": meta["name"], "version": meta["version"],
        "displayName": spec["displayName"], "description": spec["description"], "owner": spec["owner"],
        "engine": spec["engine"], "pattern": spec["pattern"], "lifecycle": spec["lifecycle"],
        "goldenPath": spec.get("goldenPath", ""), "fields": fields,
    }
    for key in ("displayNamePt", "descriptionPt", "rgdRef"):
        if spec.get(key):
            draft[key] = spec[key]
    requires = (spec.get("relations") or {}).get("requires") or []
    if requires:
        draft["requires"] = list(requires)
    return draft


# ------------------------------------------------------------------ plan
@dataclass(frozen=True)
class PublishPlan:
    op: str
    request_id: str
    requester: str
    owner: str
    directory: str
    branch: str
    actions: tuple[dict[str, str], ...]
    files: Mapping[str, bytes]
    draft_sha256: str
    policy: Mapping[str, Any]
    diff: Mapping[str, Any]
    provenance: Mapping[str, Any] = field(default_factory=dict)
    # The main commit the index and the base were read from. Empty only outside the CI (unit use).
    base_sha: str = ""

    @property
    def title(self) -> str:
        return f"service-studio({self.op}): {self.directory.removeprefix('platform/catalog/')}"

    def mr_description(self, pipeline_url: str = "") -> str:
        p, verdict = self.provenance, self.policy
        rows = [
            ("Capability", f"`{self.directory}`"), ("Operation", f"`{self.op}`"),
            ("Requester", f"@{self.requester}"), ("Owner team", f"`{self.owner}`"),
            ("Policy verdict", f"**{verdict['verdict']}**"),
            ("Sources", ", ".join(f"`{s}`" for s in p.get("sources") or []) or "-"),
            ("Origin", f"`{p.get('origin', 'form')}`" + (f" (model `{p['modelAlias']}`)" if p.get("modelAlias") else "")),
            ("Draft SHA-256", f"`{self.draft_sha256}`"), ("Compiler", f"`{COMPILER}`"),
            ("Request", f"`{self.request_id}`"),
        ]
        lines = ["Proposed by the Service Owner Studio. Nothing was applied to the cluster: this MR is the only write.", "",
                 "| | |", "|---|---|", *[f"| {k} | {v} |" for k, v in rows], ""]
        if verdict.get("reasons"):
            lines += ["**Why a platform reviewer is required:**", "", *[f"- {r}" for r in verdict["reasons"]], ""]
        d = self.diff
        lines += ["**Contract diff:**", "",
                  f"- fields added: {', '.join(d.get('fieldsAdded') or []) or '-'}",
                  f"- fields removed: {', '.join(d.get('fieldsRemoved') or []) or '-'}",
                  f"- fields changed: {', '.join(c['name'] for c in d.get('fieldsChanged') or []) or '-'}",
                  f"- metadata changed: {', '.join(c['key'] for c in d.get('metadataChanged') or []) or '-'}", "",
                  "Reverting this MR removes the change from the catalog; existing instances are not deleted."]
        if any(a["file_path"] == INDEX_PATH for a in self.actions):
            lines += ["", f"`{INDEX_PATH}` is regenerated by `platform_assistant.catalog` from the resulting catalog; CI compares its bytes."]
        if pipeline_url:
            lines += ["", f"Opened by {pipeline_url}"]
        return "\n".join(lines)


def _branch(op: str, directory: str, request_id: str) -> str:
    slug = directory.removeprefix("platform/catalog/").replace("/", "-")
    return f"service-studio/{op}-{slug}-{request_id[:8]}"


def plan_publish(op: str, *, draft: Mapping[str, Any] | None, base: Mapping[str, Any] | None,
                 existing: tuple[str, ...] = (), requester: str, request_id: str,
                 compositions: Mapping[str, Composition], provenance: Mapping[str, Any] | None = None) -> PublishPlan:
    """Pure. `base` is the draft on `main` (None on create), `existing` the files present there."""
    if op not in OPS:
        raise PublishRefused("invalid_draft", f"op must be one of {OPS}")
    if not _REQUEST_ID.fullmatch(request_id or ""):
        raise PublishRefused("invalid_draft", "request id must be 32 hex characters")
    if op in DRAFT_OPS:
        validation = validate_draft(draft, compositions)
        if not validation.valid:
            first = validation.errors[0]
            raise PublishRefused("invalid_draft", f"{first.code} at {first.path or '/'}")
        target = normalize_draft(dict(draft))  # type: ignore[arg-type]
    else:
        if base is None:
            raise PublishRefused("not_found", "there is no package on main to change")
        target = normalize_draft(dict(base))
    directory = package_dir(target)
    if op == OP_CREATE and existing:
        raise PublishRefused("already_exists", f"{directory} already exists on {TARGET_BRANCH}; evolve it instead")
    if op != OP_CREATE and not existing:
        raise PublishRefused("not_found", f"{directory} is not on {TARGET_BRANCH}")
    if op == OP_EVOLVE and base is not None:
        if package_dir(normalize_draft(dict(base))) != directory:
            raise PublishRefused("invalid_draft", "evolve keeps domain, name and version; a new version is a create")
        broken = breaking_changes(normalize_draft(dict(base)), target)
        if broken:
            raise PublishRefused("breaking_change", "; ".join(broken) + ". Publish a new version instead.")
    files: dict[str, bytes] = {}
    if op == OP_RETIRE:
        actions = tuple({"action": "delete", "file_path": path} for path in sorted(existing))
    else:
        files = compile_package(target, compositions, "deprecated" if op == OP_DEPRECATE else None)
        if op == OP_DEPRECATE:
            files = {p: b for p, b in files.items() if p.endswith(("capability.yaml", "docs.md"))}
        present = set(existing)
        actions = tuple({"action": "update" if path in present else "create", "file_path": path,
                         "content": base64.b64encode(content).decode("ascii"), "encoding": "base64"}
                        for path, content in sorted(files.items()))
    assert_publish_paths([a["file_path"] for a in actions], directory)
    sha = draft_sha256(target)
    return PublishPlan(op=op, request_id=request_id, requester=requester, owner=str(target["owner"]),
                       directory=directory, branch=_branch(op, directory, request_id), actions=actions,
                       files=files, draft_sha256=sha, policy=policy_verdict(target, base, op),
                       diff=diff_drafts(normalize_draft(dict(base)) if base else None, target),
                       provenance=dict(provenance or {}))


def verify_recompiled(plan: PublishPlan, stored_sha256: str) -> str:
    """Empty when the CI recompilation matches what the user previewed; else the reason (I2)."""
    if plan.op in DRAFT_OPS and plan.draft_sha256 != stored_sha256:
        return f"compiled draft {plan.draft_sha256[:12]} differs from the previewed {str(stored_sha256)[:12]}"
    return ""


# ------------------------------------------------------------------ capability index (Platform Assistant cache)
def assert_publish_paths(paths: list[str] | tuple[str, ...], directory: str) -> None:
    """Closed allowlist of one Studio commit: files of THIS package, plus the generated index."""
    package = [p for p in paths if p != INDEX_PATH]
    for path in package:
        if not path.startswith(directory + "/"):
            raise ValueError(f"refusing to write outside {directory}: {path[:120]!r}")
    assert_package_paths(package)


def regenerate_index(repo_root: Path, package_actions: tuple[dict[str, str], ...]) -> bytes:
    """Index bytes of the catalog this commit produces. Pure: same checkout and actions, same bytes.

    The overlay copies only what `build_index` reads and applies the package actions exactly as
    the commit will, so a deprecate that rewrites two files keeps the other two.
    """
    from platform_assistant import catalog  # the canonical builder; there is no other way in

    with tempfile.TemporaryDirectory(prefix="studio-index-") as tmp:
        tree = Path(tmp)
        for rel in _INDEX_INPUTS:
            if (repo_root / rel).is_dir():
                shutil.copytree(repo_root / rel, tree / rel)
        for action in package_actions:
            target = tree / action["file_path"]
            if action["action"] == "delete":
                target.unlink(missing_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(base64.b64decode(action["content"]))
        return catalog.render_index(catalog.build_index(tree)).encode("utf-8")


def _split(plan: PublishPlan) -> tuple[tuple[dict[str, str], ...], list[dict[str, str]]]:
    package = tuple(a for a in plan.actions if a["file_path"] != INDEX_PATH)
    return package, [a for a in plan.actions if a["file_path"] == INDEX_PATH]


def with_capability_index(plan: PublishPlan, repo_root: Path) -> PublishPlan:
    """The plan plus the regenerated index, when the package changes it. Any index already in the plan is discarded."""
    package, _ = _split(plan)
    assert_publish_paths([a["file_path"] for a in package], plan.directory)
    current_file = repo_root / INDEX_PATH
    current = current_file.read_bytes() if current_file.is_file() else None
    index = regenerate_index(repo_root, package)
    if index == current:
        return replace(plan, actions=package)
    return replace(plan, actions=package + ({
        "action": "update" if current is not None else "create", "file_path": INDEX_PATH,
        "content": base64.b64encode(index).decode("ascii"), "encoding": "base64"},))


def verify_index(plan: PublishPlan, repo_root: Path) -> str:
    """Empty when the index the commit carries is byte-for-byte the regenerated one; else the reason."""
    package, written = _split(plan)
    try:
        assert_publish_paths([a["file_path"] for a in plan.actions], plan.directory)
    except ValueError as error:
        return str(error)
    if len(written) > 1 or any(a.get("action") == "delete" or a.get("encoding") != "base64" for a in written):
        return f"{INDEX_PATH} may be written once, as base64 content"
    current_file = repo_root / INDEX_PATH
    current = current_file.read_bytes() if current_file.is_file() else None
    carried = base64.b64decode(written[0]["content"]) if written else current
    if carried != regenerate_index(repo_root, package):
        return f"{INDEX_PATH} in the commit differs from the one regenerated from the catalog"
    return ""


# ------------------------------------------------------------------ GitLab drive
@dataclass(frozen=True)
class PublishResult:
    status: str        # one of PERSISTED_STATUSES
    mr_url: str
    detail: str
    code: str = ""
    resumed: bool = False


def _q(value: str) -> str:
    return urllib.parse.quote(value, safe="")


def existing_files(gitlab: GitLabPort, directory: str, ref: str = TARGET_BRANCH) -> tuple[str, ...]:
    found = []
    for name in FILES:
        path = f"{directory}/{name}"
        status, _ = gitlab.call("GET", f"/repository/files/{_q(path)}?ref={_q(ref)}")
        if status == 200:
            found.append(path)
        elif status != 404:
            raise PublishRefused("gitlab_error", f"GET {path} returned {status}")
    return tuple(found)


def _head(gitlab: GitLabPort) -> str:
    status, body = gitlab.call("GET", f"/repository/branches/{TARGET_BRANCH}")
    sha = (body.get("commit") or {}).get("id") if status == 200 and isinstance(body, dict) else None
    if not isinstance(sha, str) or not _SHA.fullmatch(sha):
        raise PublishRefused("gitlab_error", f"could not read the head of {TARGET_BRANCH}: HTTP {status}")
    return sha


def scaffold(gitlab: GitLabPort, plan: PublishPlan, *, pipeline_url: str = "") -> PublishResult:
    try:
        status, branch = gitlab.call("GET", f"/repository/branches/{_q(plan.branch)}")
        resumed = status == 200
        if status == 404:
            start: dict[str, str] = {"start_branch": TARGET_BRANCH}
            if plan.base_sha:
                # Recheck against GitLab NOW, not against the job's checkout: the index in the plan
                # was built from base_sha, so a moved main must stop the write, not shift its base.
                head = _head(gitlab)
                if head != plan.base_sha:
                    raise PublishRefused("stale_base", f"{TARGET_BRANCH} moved from {plan.base_sha[:12]} to {head[:12]} "
                                                       "after the index was generated; nothing was written")
                start = {"start_sha": plan.base_sha}
            status, _ = gitlab.call("POST", "/repository/commits", {
                "branch": plan.branch, **start, "actions": list(plan.actions),
                "commit_message": f"{plan.title}\n\nDraft {plan.draft_sha256}. Requester @{plan.requester}.",
            })
            if status not in (200, 201):
                raise PublishRefused("gitlab_error", f"commit returned {status}")
        elif status != 200:
            raise PublishRefused("gitlab_error", f"branch lookup returned {status}")
        status, mrs = gitlab.call("GET", f"/merge_requests?state=all&source_branch={_q(plan.branch)}")
        for mr in mrs if status == 200 and isinstance(mrs, list) else []:
            state, url = mr.get("state"), str(mr.get("web_url", ""))
            if state == "opened":
                return PublishResult("mr_open", url, "merge request already open", resumed=True)
            if state == "merged":
                raise PublishRefused("mr_merged", f"{plan.branch} was already merged")
            if state == "closed":
                raise PublishRefused("mr_closed", f"{plan.branch} was closed without merging; open a new request")
        status, mr = gitlab.call("POST", "/merge_requests", {
            "source_branch": plan.branch, "target_branch": TARGET_BRANCH, "title": plan.title,
            "description": plan.mr_description(pipeline_url), "labels": MR_LABELS, "remove_source_branch": True,
        })
        if status not in (200, 201) or not isinstance(mr, dict):
            raise PublishRefused("gitlab_error", f"merge request returned {status}")
        return PublishResult("mr_open", str(mr.get("web_url", "")), "merge request opened", resumed=resumed)
    except PublishRefused as refusal:
        return PublishResult("failed", "", refusal.detail, refusal.code)

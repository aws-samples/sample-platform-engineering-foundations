"""Compile a validated ServiceDraft into the capability package, deterministically.

One draft in, four files out, byte-identical on every run: `capability.yaml`, `schema.json`,
`examples/instance.yaml` and `docs.md`. The fifth artifact of the contract, the RGD, is not
generated: the draft points at an existing composition with `rgdRef`, and the validator has
already proved the form only asks for what that composition accepts. Writing a new RGD
creates AWS resources, which is a platform-team change with its own review (issue #11,
non-goals), so the Studio never produces one.

YAML is emitted by hand with JSON-quoted scalars (valid YAML), because the Lambda bundle has
no YAML library and a stable byte layout is what makes "preview == what the CI recompiles"
checkable with a hash.
"""
from __future__ import annotations

import hashlib
import json
import re
from typing import Any, Mapping

from .compositions import Composition
from .contract import (
    ARGO_APPLICATION, COMPILER, DELETION_POLICY, KRO_API_VERSION, READY_CONDITION, TARGET_ACCOUNTS,
)

PACKAGE_ROOT = "platform/catalog"
FILES = ("capability.yaml", "schema.json", "examples/instance.yaml", "docs.md")
NAME_SCHEMA_PATTERN = "^[a-z0-9]([-a-z0-9]*[a-z0-9])?$"
_JSON_TYPES = {"string": "string", "integer": "integer", "boolean": "boolean", "stringMap": "object", "stringList": "array"}


def canonical_bytes(draft: Mapping[str, Any]) -> bytes:
    return json.dumps(draft, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")


def draft_sha256(draft: Mapping[str, Any]) -> str:
    return hashlib.sha256(canonical_bytes(draft)).hexdigest()


def package_dir(draft: Mapping[str, Any]) -> str:
    return f"{PACKAGE_ROOT}/{draft['domain']}/{draft['name']}/{draft['version']}"


def kind_of(draft: Mapping[str, Any], composition: Composition | None) -> str:
    if composition is not None:
        return composition.kind
    return "".join(part.capitalize() for part in str(draft["name"]).split("-"))


def _q(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def _yaml_value(value: Any) -> str:
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_q(k)}: {_q(v)}" for k, v in sorted(value.items())) + "}"
    return _q(value)


def compile_capability(draft: Mapping[str, Any], sha: str, lifecycle: str | None = None) -> bytes:
    spec_lifecycle = lifecycle or draft["lifecycle"]
    lines = [
        "# Generated by the Service Owner Studio from a reviewed ServiceDraft. Edit the draft, not this file.",
        "apiVersion: platform.appmod/v1",
        "kind: Capability",
        "metadata:",
        f"  name: {draft['name']}",
        f"  domain: {draft['domain']}",
        f"  version: {draft['version']}",
        "  annotations:",
        f"    platform.appmod/compiler: {_q(COMPILER)}",
        f"    platform.appmod/draft-sha256: {_q(sha)}",
        "spec:",
        f"  displayName: {_q(draft['displayName'])}",
        f"  displayNamePt: {_q(draft.get('displayNamePt') or draft['displayName'])}",
        f"  description: {_q(draft['description'])}",
        f"  descriptionPt: {_q(draft.get('descriptionPt') or draft['description'])}",
        f"  owner: {draft['owner']}",
        f"  engine: {draft['engine']}",
        f"  pattern: {_q(draft['pattern'])}",
        f"  lifecycle: {spec_lifecycle}",
        f"  deletionPolicy: {DELETION_POLICY}",
        f"  targetAccounts: [{', '.join(_q(a) for a in TARGET_ACCOUNTS)}]",
    ]
    if draft.get("rgdRef"):
        lines.append(f"  rgdRef: {draft['rgdRef']}")
    lines += [
        f"  goldenPath: {draft['goldenPath']}",
        "  relations:",
        f"    requires: [{', '.join(_q(r) for r in draft.get('requires') or [])}]",
        "    composes: []",
    ]
    if draft.get("rgdRef"):
        lines += ["  status:", f"    argoApplication: {ARGO_APPLICATION}", f"    readyCondition: {READY_CONDITION}"]
    return ("\n".join(lines) + "\n").encode("utf-8")


def _anchored(pattern: str) -> str:
    return pattern if pattern.startswith("^") and pattern.endswith("$") else f"^(?:{pattern})$"


def schema_document(draft: Mapping[str, Any], composition: Composition | None) -> dict[str, Any]:
    properties: dict[str, Any] = {}
    for field in draft["fields"]:
        prop: dict[str, Any] = {"type": _JSON_TYPES[field["type"]]}
        if field["type"] == "stringMap":
            prop["additionalProperties"] = {"type": "string"}
        if field["type"] == "stringList":
            prop["items"] = {"type": "string"}
        for key in ("title", "description", "enum", "minimum", "maximum", "default"):
            if key in field:
                prop[key] = field[key]
        if field["name"] == "name" and "pattern" not in field:
            prop["pattern"] = NAME_SCHEMA_PATTERN
        elif "pattern" in field:
            prop["pattern"] = _anchored(field["pattern"])
        if "example" in field:
            prop["examples"] = [field["example"]]
        properties[field["name"]] = prop
    return {
        "$schema": "http://json-schema.org/draft-07/schema#",
        "title": kind_of(draft, composition),
        "type": "object",
        "required": sorted(f["name"] for f in draft["fields"] if f.get("required")),
        "properties": properties,
        "additionalProperties": False,
    }


def example_values(draft: Mapping[str, Any]) -> dict[str, Any]:
    values: dict[str, Any] = {}
    for field in draft["fields"]:
        if "example" in field:
            values[field["name"]] = field["example"]
        elif field.get("required") and "default" in field:
            values[field["name"]] = field["default"]
    return values


def compile_example(draft: Mapping[str, Any], composition: Composition | None) -> bytes:
    values = example_values(draft)
    instance = str(values.get("name") or f"{draft['name']}-example")
    lines = [
        "# Generated by the Service Owner Studio: an instance that validates against schema.json.",
        "# The namespace is assigned by the platform policy, so it is not part of the example.",
        f"apiVersion: {KRO_API_VERSION}",
        f"kind: {kind_of(draft, composition)}",
        "metadata:",
        f"  name: {instance}",
        "spec:",
    ]
    lines += [f"  {key}: {_yaml_value(value)}" for key, value in values.items()] or ["  {}"]
    return ("\n".join(lines) + "\n").encode("utf-8")


def _cell(value: Any) -> str:
    text = "" if value is None else (value if isinstance(value, str) else json.dumps(value, ensure_ascii=False))
    return text.replace("|", "\\|") or "-"


def compile_docs(draft: Mapping[str, Any], sha: str, lifecycle: str | None = None) -> bytes:
    docs = draft.get("docs") or {}
    lines = [
        f"# {draft['displayName']}",
        "",
        draft["description"],
        "",
        "| | |",
        "|---|---|",
        f"| Owner | `{draft['owner']}` |",
        f"| Version | `{draft['version']}` |",
        f"| Lifecycle | `{lifecycle or draft['lifecycle']}` |",
        f"| Engine | `{draft['engine']}` ({_cell(draft['pattern'])}) |",
        f"| Composition | `{draft.get('rgdRef') or 'none yet (planned)'}` |",
        f"| Requires | {', '.join(f'`{r}`' for r in draft.get('requires') or []) or '-'} |",
        f"| Deletion policy | `{DELETION_POLICY}` |",
        "",
    ]
    if docs.get("overview"):
        lines += ["## Overview", "", docs["overview"].strip(), ""]
    lines += ["## Inputs", "", "| Field | Type | Required | Default | Description |", "|---|---|---|---|---|"]
    for field in draft["fields"]:
        text = " ".join(filter(None, [field.get("description", ""), f"One of: {', '.join(field['enum'])}." if "enum" in field else ""]))
        lines.append(f"| `{field['name']}` | {field['type']} | {'yes' if field.get('required') else 'no'} | "
                     f"{_cell(field.get('default'))} | {_cell(text)} |")
    lines.append("")
    if docs.get("usage"):
        lines += ["## Usage", "", docs["usage"].strip(), ""]
    lines += ["## Provenance", "", f"Compiled by `{COMPILER}` from draft `{sha[:12]}`. Changes go through a merge request; "
              "reverting it removes the capability from the catalog and leaves existing instances untouched.", ""]
    return "\n".join(lines).encode("utf-8")


def compile_package(draft: Mapping[str, Any], compositions: Mapping[str, Composition],
                    lifecycle: str | None = None) -> dict[str, bytes]:
    """Every file of the package, keyed by repository path. Pure: no I/O, no clock."""
    composition = compositions.get(draft["rgdRef"]) if draft.get("rgdRef") else None
    sha = draft_sha256(draft)
    root = package_dir(draft)
    schema = (json.dumps(schema_document(draft, composition), ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    return {
        f"{root}/capability.yaml": compile_capability(draft, sha, lifecycle),
        f"{root}/schema.json": schema,
        f"{root}/examples/instance.yaml": compile_example(draft, composition),
        f"{root}/docs.md": compile_docs(draft, sha, lifecycle),
    }



def diff_drafts(base: Mapping[str, Any] | None, new: Mapping[str, Any]) -> dict[str, Any]:
    """What a reviewer needs to see, at the level of meaning, not of bytes."""
    base_fields = {f["name"]: f for f in (base or {}).get("fields", [])}
    new_fields = {f["name"]: f for f in new["fields"]}
    changed = []
    for name in sorted(set(base_fields) & set(new_fields)):
        keys = sorted(k for k in set(base_fields[name]) | set(new_fields[name]) if base_fields[name].get(k) != new_fields[name].get(k))
        if keys:
            changed.append({"name": name, "changes": [{"key": k, "before": base_fields[name].get(k), "after": new_fields[name].get(k)} for k in keys]})
    metadata = sorted(k for k in set(new) | set(base or {}) if k != "fields" and (base or {}).get(k) != new.get(k)) if base else []
    return {
        "op": "evolve" if base else "create",
        "fieldsAdded": sorted(set(new_fields) - set(base_fields)),
        "fieldsRemoved": sorted(set(base_fields) - set(new_fields)),
        "fieldsChanged": changed,
        "metadataChanged": [{"key": k, "before": (base or {}).get(k), "after": new.get(k)} for k in metadata],
    }


def breaking_changes(base: Mapping[str, Any], new: Mapping[str, Any]) -> list[str]:
    """Changes that would invalidate an existing instance. Same version: refused (catalog rule)."""
    reasons: list[str] = []
    base_fields = {f["name"]: f for f in base.get("fields", [])}
    new_fields = {f["name"]: f for f in new["fields"]}
    for name, before in base_fields.items():
        after = new_fields.get(name)
        if after is None:
            reasons.append(f"field {name} removed")
            continue
        if after["type"] != before["type"]:
            reasons.append(f"field {name} changed type")
        if after.get("required") and not before.get("required"):
            reasons.append(f"field {name} became required")
        if "enum" in after and not set(before.get("enum") or after["enum"]) <= set(after["enum"]):
            reasons.append(f"field {name} narrowed its options")
        if "pattern" in after and after.get("pattern") != before.get("pattern"):
            reasons.append(f"field {name} changed its pattern")
        for bound, tighter in (("minimum", lambda a, b: a > b), ("maximum", lambda a, b: a < b)):
            if bound in after and (bound not in before or tighter(after[bound], before[bound])):
                reasons.append(f"field {name} tightened {bound}")
    for name, after in new_fields.items():
        if name not in base_fields and after.get("required") and "default" not in after:
            reasons.append(f"new field {name} is required without a default")
    if base.get("rgdRef") and new.get("rgdRef") != base.get("rgdRef"):
        reasons.append("composition changed")
    return reasons


def policy_verdict(new: Mapping[str, Any], base: Mapping[str, Any] | None, op: str) -> dict[str, Any]:
    """Which review the MR needs. The Studio never approves anything; this only routes it.

    `elevated_review` is the issue's non-goal made mechanical: binding a composition (which
    creates AWS resources) as self-service, adding a dependency, changing ownership or
    removing the capability always gets a human platform reviewer.
    """
    reasons: list[str] = []
    if op == "retire":
        reasons.append("removes the capability from the catalog")
    if new.get("rgdRef") and (base is None or base.get("rgdRef") != new.get("rgdRef")):
        reasons.append(f"binds {new['rgdRef']}, which creates AWS resources, as self-service")
    if new.get("lifecycle") == "preview" and (base is None or base.get("lifecycle") != "preview"):
        reasons.append("makes the capability provisionable (preview)")
    if base is not None and base.get("owner") != new.get("owner"):
        reasons.append("changes the owner team")
    added = set(new.get("requires") or []) - set((base or {}).get("requires") or [])
    if added:
        reasons.append(f"adds dependencies: {', '.join(sorted(added))}")
    return {"verdict": "elevated_review" if reasons else "standard_review", "reasons": reasons,
            "humanReviewRequired": True}


_SAFE_PATH = re.compile(r"platform/catalog/[a-z]+/[a-z][a-z0-9-]*[a-z0-9]/v[1-9][0-9]?/(?:capability\.yaml|schema\.json|docs\.md|examples/instance\.yaml)")


def assert_package_paths(paths: list[str] | tuple[str, ...] | Any) -> None:
    for path in paths:
        if not _SAFE_PATH.fullmatch(path) or ".." in path.split("/"):
            raise ValueError(f"refusing to write outside a catalog package: {path[:120]!r}")

export function translate(text: string, locale: Locale): string {
  return locale === 'pt-BR' ? (pt[text] ?? text) : text;
}

interface I18nValue {
  locale: Locale;
  setLocale(locale: Locale): void;
  t(text: string): string;
}

const Context = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }): JSX.Element {
  const [locale, setLocaleState] = useState<Locale>(() => localStorage.getItem('agent-platform-locale') === 'en-US' ? 'en-US' : 'pt-BR');
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale(next) {
      localStorage.setItem('agent-platform-locale', next);
      setLocaleState(next);
    },
    t(text) {
      return translate(text, locale);
    },
  }), [locale]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(Context);
  if (!value) throw new Error('useI18n must be used inside I18nProvider');
  return value;
}
